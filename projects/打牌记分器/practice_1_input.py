def get_player_count():
    """获取玩家人数（1~10 的整数，直接回车默认返回 6）。

    功能要求：
    1. 反复提示用户输入："请输入玩家人数（1~10，直接回车默认 6 人）: "
    2. 去掉首尾空格后，如果用户直接回车（空字符串），默认当成 "6"
    3. 如果输入是纯数字，且转成整数后在 1 到 10 之间，就返回这个整数（int）
    4. 否则打印提示："请输入 1~10 之间的数字。" 然后继续让用户重输

    输入样例与期望行为：
    - 直接回车        -> 返回整数 6
    - 输入 "abc"      -> 打印提示，继续让用户重输
    - 输入 "0" / "15" -> 打印提示，继续让用户重输
    - 输入 "4"        -> 返回整数 4
    """
    # TODO: 请在这里补全代码（约 5~6 行）
    while True:
        raw = input("请输入玩家人数（1~10，直接回车默认 6 人）: ").strip() or "6"
        if raw.isdigit() and 1 <= int(raw) <= 10:
          return int(raw)
        else:
            print("请输入 1~10 之间的数字。")  


# --- 下方是测试外壳，不用修改 ---
if __name__ == "__main__":
    count = get_player_count()
    print(f"\n设置成功！玩家人数 = {count}，数据类型 = {type(count)}")
    assert type(count) is int and 1 <= count <= 10, "返回值必须是 1~10 的整数哦！"
    print("✅ 测试通过！建议多跑两次，测测：直接回车、输字母、输 0、输 11。")
